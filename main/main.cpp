// Core 0: continuous sampling into a ping-pong buffer
extern "C" void core0_sampling_task(void *pvParameters) {
    uint8_t reg_addr = MPU6050_ACCEL_XOUT_H;
    uint8_t data[6];
    int16_t accel_x;
    int sample_index = 0;
    int active_buffer = 0;

    uint32_t i2c_success_count = 0;
    uint32_t i2c_fail_count = 0;
    TickType_t buffer_start_tick = xTaskGetTickCount();

    while (1) {
        esp_err_t ret = i2c_master_write_read_device(I2C_MASTER_NUM, MPU6050_ADDR, &reg_addr, 1, data, 6, portMAX_DELAY);

        if (ret == ESP_OK) {
            i2c_success_count++;
            accel_x = (data[0] << 8) | data[1];

            accel_data_buffer[active_buffer][sample_index] = (float)accel_x;
            sample_index++;

            if (sample_index >= BUFFER_SIZE) {
                sample_index = 0;

                TickType_t now = xTaskGetTickCount();
                uint32_t elapsed_ms = (now - buffer_start_tick) * portTICK_PERIOD_MS;
                printf("DEBUG:success=%lu,fail=%lu,elapsed_ms=%lu\n",
                       (unsigned long)i2c_success_count,
                       (unsigned long)i2c_fail_count,
                       (unsigned long)elapsed_ms);

                i2c_success_count = 0;
                i2c_fail_count = 0;
                buffer_start_tick = now;

                int finished_buffer = active_buffer;
                xQueueSend(ready_buffer_queue, &finished_buffer, 0);
                active_buffer = 1 - active_buffer;
            }
        } else {
            i2c_fail_count++;
        }
        vTaskDelay(10 / portTICK_PERIOD_MS);
    }
}

void calculate_fft(float *real, float *imag, int n) {
    int j = 0;
    for (int i = 0; i < n; i++) {
        if (i < j) {
            float temp = real[i]; real[i] = real[j]; real[j] = temp;
            temp = imag[i]; imag[i] = imag[j]; imag[j] = temp;
        }
        int m = n >> 1;
        while (m >= 1 && j >= m) { j -= m; m >>= 1; }
        j += m;
    }
    for (int size = 2; size <= n; size <<= 1) {
        float angle = -2.0 * 3.14159265 / size;
        float wreal = cos(angle), wimag = sin(angle);
        for (int i = 0; i < n; i += size) {
            float uright_re = 1.0, uright_im = 0.0;
            for (int k = 0; k < size / 2; k++) {
                int idx1 = i + k, idx2 = i + k + size / 2;
                float treal = real[idx2] * uright_re - imag[idx2] * uright_im;
                float timag = real[idx2] * uright_im + imag[idx2] * uright_re;
                real[idx2] = real[idx1] - treal; imag[idx2] = imag[idx1] - timag;
                real[idx1] += treal; imag[idx1] += timag;
                float next_re = uright_re * wreal - uright_im * wimag;
                uright_im = uright_re * wimag + uright_im * wreal; uright_re = next_re;
            }
        }
    }
}

void classify_motor_state(float* my_fft_array) {
    signal_t features_signal;

    int err = numpy::signal_from_buffer(my_fft_array, EI_CLASSIFIER_DSP_INPUT_FRAME_SIZE, &features_signal);
    if (err != 0) {
        printf("Failed to create signal from buffer\n");
        return;
    }

    ei_impulse_result_t result = { 0 };

    err = run_classifier(&features_signal, &result, false);
    if (err != EI_IMPULSE_OK) {
        printf("ERR: Failed to run classifier\n");
        return;
    }

    float normal_score = result.classification[1].value;

    printf("Classification results:\n");
    printf("  Anomaly: %.5f\n", result.classification[0].value);
    printf("  Normal: %.5f\n", result.classification[1].value);

    if (normal_score >= 0.80f) {
        gpio_set_level(LED_GREEN_PIN, 1);
        gpio_set_level(LED_ORANGE_PIN, 0);
        gpio_set_level(LED_RED_PIN, 0);
    } else if (normal_score >= 0.60f && normal_score < 0.80f) {
        printf("WARNING: Motor performance degrading (Score: %.2f)\n", normal_score);
        gpio_set_level(LED_GREEN_PIN, 0);
        gpio_set_level(LED_ORANGE_PIN, 1);
        gpio_set_level(LED_RED_PIN, 0);
    } else {
        printf("!!! EMERGENCY STOP: NORMAL SCORE DROPPED TO %.2f !!!\n", normal_score);
        gpio_set_level(LED_GREEN_PIN, 0);
        gpio_set_level(LED_ORANGE_PIN, 0);
        gpio_set_level(LED_RED_PIN, 1);

        // Uncomment to actually cut power to the motor on critical fault:
        ledc_set_duty(LEDC_MODE, LEDC_CHANNEL, 0);
        ledc_update_duty(LEDC_MODE, LEDC_CHANNEL);
    }
}

// Core 1: FFT + classification on whichever buffer is ready
extern "C" void core1_processing_task(void *pvParameters) {
    int buffer_to_process;
    float imag_buffer[BUFFER_SIZE];
    float magnitude[BUFFER_SIZE / 2];  // 128 bins - matches model input size

    // Skip the first buffer: it may contain stale/settling readings
    // from right after sensor wake-up.
    int buffers_to_skip = 1;

    while (1) {
        if (xQueueReceive(ready_buffer_queue, &buffer_to_process, portMAX_DELAY) == pdTRUE) {

            if (buffers_to_skip > 0) {
                printf("Skipping initial buffer to flush old sensor data...\n");
                buffers_to_skip--;
                continue;
            }

            for (int i = 0; i < BUFFER_SIZE; i++) {
                imag_buffer[i] = 0.0f;
            }

            calculate_fft(accel_data_buffer[buffer_to_process], imag_buffer, BUFFER_SIZE);

            for (int i = 0; i < BUFFER_SIZE / 2; i++) {
                float r = accel_data_buffer[buffer_to_process][i];
                float im = imag_buffer[i];
                magnitude[i] = sqrtf(r * r + im * im);
            }

            classify_motor_state(magnitude);

            for (int i = 0; i < BUFFER_SIZE / 2; i++) {
                printf("%.4f", magnitude[i]);
                if (i < (BUFFER_SIZE / 2) - 1) {
                    printf(",");
                }
            }
            printf("\n");
        }
    }
}

// ==========================================
// Main Application Entry Point
// ==========================================
extern "C" void app_main() {
    init_motor_pwm();
    init_leds();
    i2c_master_init();

    ready_buffer_queue = xQueueCreate(NUM_BUFFERS, sizeof(int));
    if (ready_buffer_queue == NULL) {
        printf("Failed to create queue!\n");
        return;
    }

    ledc_set_duty(LEDC_MODE, LEDC_CHANNEL, 204);
    ledc_update_duty(LEDC_MODE, LEDC_CHANNEL);
    printf("Motor started. Waiting 2 seconds for stabilization...\n");
    vTaskDelay(2000 / portTICK_PERIOD_MS);

    printf("Resetting and waking sensor...\n");
    mpu6050_reset_and_wake();

    mpu6050_health_check();

    printf("Starting AI Sampling...\n");

    xTaskCreatePinnedToCore(core0_sampling_task, "Core_0_Sampling", 4096, NULL, 5, NULL, 0);
    xTaskCreatePinnedToCore(core1_processing_task, "Core_1_Processing", 10240, NULL, 4, NULL, 1);
}
