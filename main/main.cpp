// ==========================================
// Hardware settings (motor & I2C)
// ==========================================
#define MOTOR_PWM_PIN       12
#define LEDC_TIMER          LEDC_TIMER_0
#define LEDC_MODE           LEDC_LOW_SPEED_MODE
#define LEDC_CHANNEL        LEDC_CHANNEL_0
#define LEDC_DUTY_RES       LEDC_TIMER_8_BIT
#define LEDC_FREQUENCY      5000

#define I2C_MASTER_SCL_IO           43
#define I2C_MASTER_SDA_IO           44
#define I2C_MASTER_NUM              I2C_NUM_0
#define I2C_MASTER_FREQ_HZ          100000

#define MPU6050_ADDR                0x68
#define MPU6050_PWR_MGMT_1          0x6B
#define MPU6050_WHO_AM_I            0x75
#define MPU6050_ACCEL_XOUT_H        0x3B

#define LED_GREEN_PIN  GPIO_NUM_18
#define LED_ORANGE_PIN GPIO_NUM_17
#define LED_RED_PIN    GPIO_NUM_21

// ==========================================
// Memory & RTOS
// ==========================================
// IMPORTANT: must stay 256. The model expects 128 FFT magnitude bins,
// and magnitude bins = BUFFER_SIZE / 2. Changing this breaks the model input size.
#define BUFFER_SIZE 256
#define NUM_BUFFERS 2

static float accel_data_buffer[NUM_BUFFERS][BUFFER_SIZE];
static QueueHandle_t ready_buffer_queue;

// ------------------------------------------
// Hardware init
// ------------------------------------------

void init_motor_pwm(void) {
    ledc_timer_config_t ledc_timer = {};
    ledc_timer.speed_mode       = LEDC_MODE;
    ledc_timer.timer_num        = LEDC_TIMER;
    ledc_timer.duty_resolution  = LEDC_DUTY_RES;
    ledc_timer.freq_hz          = LEDC_FREQUENCY;
    ledc_timer.clk_cfg          = LEDC_AUTO_CLK;
    ledc_timer_config(&ledc_timer);

    ledc_channel_config_t ledc_channel = {};
    ledc_channel.speed_mode     = LEDC_MODE;
    ledc_channel.channel        = LEDC_CHANNEL;
    ledc_channel.timer_sel      = LEDC_TIMER;
    ledc_channel.intr_type      = LEDC_INTR_DISABLE;
    ledc_channel.gpio_num       = MOTOR_PWM_PIN;
    ledc_channel.duty           = 0;
    ledc_channel.hpoint         = 0;
    ledc_channel_config(&ledc_channel);
}

void init_leds(void) {
    gpio_reset_pin(LED_GREEN_PIN);
    gpio_set_direction(LED_GREEN_PIN, GPIO_MODE_OUTPUT);
    gpio_reset_pin(LED_ORANGE_PIN);
    gpio_set_direction(LED_ORANGE_PIN, GPIO_MODE_OUTPUT);
    gpio_reset_pin(LED_RED_PIN);
    gpio_set_direction(LED_RED_PIN, GPIO_MODE_OUTPUT);

    gpio_set_level(LED_GREEN_PIN, 1);
    gpio_set_level(LED_ORANGE_PIN, 0);
    gpio_set_level(LED_RED_PIN, 0);
}

void i2c_master_init(void) {
    i2c_port_t i2c_master_port = (i2c_port_t)I2C_MASTER_NUM;

    i2c_config_t conf = {};
    conf.mode = I2C_MODE_MASTER;
    conf.sda_io_num = I2C_MASTER_SDA_IO;
    conf.scl_io_num = I2C_MASTER_SCL_IO;
    conf.sda_pullup_en = GPIO_PULLUP_ENABLE;
    conf.scl_pullup_en = GPIO_PULLUP_ENABLE;
    conf.master.clk_speed = I2C_MASTER_FREQ_HZ;

    i2c_param_config(i2c_master_port, &conf);
    i2c_driver_install(i2c_master_port, conf.mode, 0, 0, 0);
}

// Full reset + wake with PLL clock source (0x01, NOT 0x00).
// This is the fix for the sensor returning all zeros: 0x00 keeps the
// internal 8MHz RC oscillator as the clock source, which is much more
// sensitive to the electrical noise generated by the motor. 0x01 switches
// to the gyro-X PLL, which is far more stable under that noise.
void mpu6050_reset_and_wake(void) {
    uint8_t reset_buf[2] = {MPU6050_PWR_MGMT_1, 0x80};
    i2c_master_write_to_device(I2C_MASTER_NUM, MPU6050_ADDR, reset_buf, sizeof(reset_buf), 1000 / portTICK_PERIOD_MS);
    vTaskDelay(2000 / portTICK_PERIOD_MS);

    uint8_t wake_buf[2] = {MPU6050_PWR_MGMT_1, 0x01};
    i2c_master_write_to_device(I2C_MASTER_NUM, MPU6050_ADDR, wake_buf, sizeof(wake_buf), 1000 / portTICK_PERIOD_MS);
    vTaskDelay(2000 / portTICK_PERIOD_MS);
}

// Reads WHO_AM_I (must read 104) and Z-axis at rest (must read ~16000)
// to confirm the sensor is actually alive before starting the real tasks.
void mpu6050_health_check(void) {
    uint8_t id_reg = MPU6050_WHO_AM_I;
    uint8_t pwr_reg = MPU6050_PWR_MGMT_1;
    uint8_t accel_reg = MPU6050_ACCEL_XOUT_H;

    uint8_t test_id = 0, test_pwr = 0;
    uint8_t data[6] = {0};

    i2c_master_write_read_device(I2C_MASTER_NUM, MPU6050_ADDR, &id_reg, 1, &test_id, 1, 1000 / portTICK_PERIOD_MS);
    i2c_master_write_read_device(I2C_MASTER_NUM, MPU6050_ADDR, &pwr_reg, 1, &test_pwr, 1, 1000 / portTICK_PERIOD_MS);
    i2c_master_write_read_device(I2C_MASTER_NUM, MPU6050_ADDR, &accel_reg, 1, data, 6, 1000 / portTICK_PERIOD_MS);

    int16_t test_x = (data[0] << 8) | data[1];
    int16_t test_z = (data[4] << 8) | data[5];

    printf("\n=== SENSOR HEALTH CHECK ===\n");
    printf("1. WHO_AM_I ID  (Must be 104): %d\n", test_id);
    printf("2. POWER STATE  (Must be 1 or 0): %d\n", test_pwr);
    printf("3. ACCEL X AXIS : %d\n", test_x);
    printf("4. ACCEL Z AXIS (Must be ~16000): %d\n", test_z);
    printf("===========================\n\n");

    if (test_id != 104) {
        printf("WARNING: WHO_AM_I mismatch - check wiring/address before trusting any data!\n");
    }
}

